// Bundles the SQL migrations and seed CSVs into TypeScript so the deployed app never reads them from disk.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const journal = JSON.parse(fs.readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8")) as { entries: { tag: string }[] };
const migrations = journal.entries.map((e) => ({ tag: e.tag, sql: fs.readFileSync(path.join(root, "drizzle", `${e.tag}.sql`), "utf8") }));
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/migrations.ts"), `// Generated by scripts/embed.ts. Do not edit.\nexport const MIGRATIONS: { tag: string; sql: string }[] = ${JSON.stringify(migrations, null, 1)};\n`);
const seed: Record<string, string> = {};
for (const f of fs.readdirSync(path.join(root, "seed"))) if (f.endsWith(".csv")) seed[f] = fs.readFileSync(path.join(root, "seed", f), "utf8");
fs.writeFileSync(path.join(root, "src/generated/seed-data.ts"), `// Generated by scripts/embed.ts. Do not edit.\nexport const SEED_FILES: Record<string, string> = ${JSON.stringify(seed)};\n`);
console.log(`embedded ${migrations.length} migrations, ${Object.keys(seed).length} seed files`);
